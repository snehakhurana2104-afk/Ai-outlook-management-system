/******************************************************************************
 * aiReplyRoutes.js
 * Part 1
 * Imports + Router Initialization
 ******************************************************************************/

const express = require("express");

const router = express.Router();

/* ==========================================================================
   Controller
========================================================================== */

const aiReplyController = require(
  "../controllers/aiReplyController"
);

/******************************************************************************
 * End Part 1
 ******************************************************************************/
/******************************************************************************
 * aiReplyRoutes.js
 * Part 2
 * AI Reply Generation Routes
 ******************************************************************************/

/* ==========================================================================
   Generate AI Reply
========================================================================== */

router.post(
  "/generate",
  aiReplyController.generateReply
);

/* ==========================================================================
   Regenerate AI Reply
========================================================================== */

router.post(
  "/regenerate",
  aiReplyController.regenerateReply
);

/* ==========================================================================
   Rewrite Reply
========================================================================== */

router.post(
  "/rewrite",
  aiReplyController.rewriteReply
);

/******************************************************************************
 * End Part 2
 ******************************************************************************/
/******************************************************************************
 * aiReplyRoutes.js
 * Part 3
 * AI Utilities Routes
 ******************************************************************************/

/* ==========================================================================
   Grammar Correction
========================================================================== */

router.post(
  "/grammar",
  aiReplyController.grammarReply
);

/* ==========================================================================
   Summarize Reply
========================================================================== */

router.post(
  "/summarize",
  aiReplyController.summarizeReply
);

/* ==========================================================================
   Send Reply
========================================================================== */

router.post(
  "/send",
  aiReplyController.sendReply
);

/******************************************************************************
 * End Part 3
 ******************************************************************************/
/******************************************************************************
 * aiReplyRoutes.js
 * Part 4
 * Reply History Routes
 ******************************************************************************/

/* ==========================================================================
   Get Reply History
========================================================================== */

router.get(
  "/history/:emailId",
  aiReplyController.getReplyHistory
);

/* ==========================================================================
   Delete Reply History
========================================================================== */

router.delete(
  "/history/:id",
  aiReplyController.deleteReplyHistory
);

/******************************************************************************
 * End Part 4
 ******************************************************************************/
/******************************************************************************
 * aiReplyRoutes.js
 * Part 5
 * Export Router
 ******************************************************************************/

module.exports = router;

/******************************************************************************
 * End aiReplyRoutes.js
 ******************************************************************************/